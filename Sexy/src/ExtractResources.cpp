Image* GetImageById(int theId)
{
    // @0x1E4EB8: IDs address the live resource slots, not a cached image array.
    if (theId < 0)
        return nullptr;
    for (const ImageSlot& image : kImageSlots)
    {
        if (image.mResourceId == theId)
            return *image.mSlot;
    }
    return nullptr;
}

int GetIdByImage(Image* theImage)
{
    // @0x1E7FA4: the resource table has 757 entries, including fonts and sounds.
    int resourceId = 757;
    if (theImage == nullptr)
        return resourceId;
    for (const ImageSlot& image : kImageSlots)
    {
        if (*image.mSlot == theImage && image.mResourceId >= 0 && image.mResourceId < resourceId)
            resourceId = image.mResourceId;
    }
    return resourceId;
}

int GetSoundById(int theId)
{
    // @0x1E4EE8: resource IDs refer to slots holding the loaded sound IDs.
    for (const SoundSlot& aSound : kSoundSlots)
    {
        if (aSound.mResourceId == theId)
            return *aSound.mSlot;
    }
    return -1;
}

bool ExtractResourcesByName(ResourceManager* theResourceManager, const char* theName)
{
    if (theResourceManager == nullptr || theName == nullptr || theName[0] == '\0')
        return false;

    Sexy::String aGroupName(theName);
    ResourceManager::ResGroupMap::iterator aGroup =
        theResourceManager->mResGroupMap.find(aGroupName);
    if (aGroup == theResourceManager->mResGroupMap.end() || aGroup->second.empty())
        return false;

    int aPublished = 0;
    for (size_t aIndex = 0; aIndex < aGroup->second.size(); ++aIndex)
    {
        ResourceManager::BaseRes* aRes = aGroup->second[aIndex];
        if (aRes == nullptr)
            continue;
        const char* aId = aRes->mId.c_str();
        if (aRes->mResType == ResType_Image)
        {
            Sexy::Image** aSlot = FindImageSlot(aId);
            if (aSlot == nullptr)
                continue;
            ResourceManager::ImageRes* aImage = static_cast<ResourceManager::ImageRes*>(aRes);
            *aSlot = aImage->mImage.mImage;
            if (*aSlot != nullptr)
                ++aPublished;
        }
        else if (aRes->mResType == ResType_Font)
        {
            Sexy::Font** aSlot = FindFontSlot(aId);
            if (aSlot == nullptr)
                continue;
            ResourceManager::FontRes* aFont = static_cast<ResourceManager::FontRes*>(aRes);
            *aSlot = aFont->mFont;
            if (*aSlot != nullptr)
                ++aPublished;
        }
        else if (aRes->mResType == ResType_Sound)
        {
            int* aSlot = FindSoundSlot(aId);
            if (aSlot == nullptr)
                continue;
            ResourceManager::SoundRes* aSound = static_cast<ResourceManager::SoundRes*>(aRes);
            *aSlot = aSound->mSoundId;
            if (*aSlot >= 0)
                ++aPublished;
        }
    }

    fprintf(stderr, "ExtractResourcesByName: '%s' published %d resource(s)\n", theName, aPublished);
    fflush(stderr);
    return aPublished > 0;
}

