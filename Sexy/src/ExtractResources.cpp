bool IdMatches(const char* theSlotName, const char* theId)
{
    if (theSlotName == nullptr || theId == nullptr)
        return false;
    if (strcmp(theSlotName, theId) == 0)
        return true;
    // The manifest stores the id after idprefix, so IMAGE_LOADBAR_GRASS is
    // recorded as LOADBAR_GRASS. Both spellings name the same global.
    const char* aTail = theSlotName;
    if (strncmp(aTail, "IMAGE_", 6) == 0)
        aTail += 6;
    else if (strncmp(aTail, "FONT_", 5) == 0)
        aTail += 5;
    else if (strncmp(aTail, "SOUND_", 6) == 0)
        aTail += 6;
    return strcmp(aTail, theId) == 0;
}

Sexy::Image** FindImageSlot(const char* theId)
{
    if (theId == nullptr)
        return nullptr;
    for (int i = 0; i < (int)(sizeof(kImageSlots) / sizeof(kImageSlots[0])); ++i)
    {
        if (IdMatches(kImageSlots[i].mName, theId))
            return kImageSlots[i].mSlot;
    }
    return nullptr;
}

Sexy::Font** FindFontSlot(const char* theId)
{
    if (theId == nullptr)
        return nullptr;
    for (int i = 0; i < (int)(sizeof(kFontSlots) / sizeof(kFontSlots[0])); ++i)
    {
        if (IdMatches(kFontSlots[i].mName, theId))
            return kFontSlots[i].mSlot;
    }
    return nullptr;
}

int* FindSoundSlot(const char* theId)
{
    if (theId == nullptr)
        return nullptr;
    for (int i = 0; i < (int)(sizeof(kSoundSlots) / sizeof(kSoundSlots[0])); ++i)
    {
        if (IdMatches(kSoundSlots[i].mName, theId))
            return kSoundSlots[i].mSlot;
    }
    return nullptr;
}

